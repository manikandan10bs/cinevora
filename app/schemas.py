class MasterCatalogMovieItem(BaseModel):
    """Single movie record from Movies_Master_Cleaned.csv."""
    catalog_id: str = Field(..., description="Unique Cinevora catalog identifier e.g. CINEVORA-0000001")
    movie_id: Any = Field(..., description="Source dataset movie identifier")
    industry: str = Field(..., description="Film industry: Bollywood, Tamil, Telugu, Malayalam, Hollywood, Kannada")
