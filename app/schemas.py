    movie_id: Union[int, str] = Field(..., description="Unique MovieLens integer or Master Catalog identifier")
    movie_title: str = Field(..., description="Full title and release year of the movie")
    release_date: Optional[str] = Field(None, description="Release date in DD-Mon-YYYY format")
    release_year: Optional[int] = Field(None, description="Extracted release year")
